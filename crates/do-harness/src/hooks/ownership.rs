//! Who owns the files at the effective git hook paths.
//!
//! A repository may delegate its hooks to another manager: the pre-commit
//! framework writes its own wrapper, and `core.hooksPath` can point at a shared
//! hook directory. `doctor` treats a recognised delegate as healthy instead of
//! reporting a missing do-harness hook, and `hook install` names the delegate
//! when it refuses to clobber the foreign wrapper.

use std::fs;
use std::path::Path;

use crate::hook_script::MARKER;

/// Configuration file that declares pre-commit as the hook owner.
pub const PRE_COMMIT_CONFIG: &str = ".pre-commit-config.yaml";

/// Substring present in every hook wrapper the pre-commit framework generates.
const PRE_COMMIT_WRAPPER_MARKER: &str = "File generated by pre-commit";

/// Owner of the file at a hook path.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum HookOwner {
    /// No file at the path.
    Absent,
    /// A hook managed by do-harness (carries the managed-hook [`MARKER`]).
    Managed,
    /// A hook owned by the pre-commit framework.
    PreCommit,
    /// A foreign hook in the directory named by `core.hooksPath`.
    HooksPath,
    /// A foreign hook whose owner is not recognised.
    Foreign,
}

impl HookOwner {
    /// Whether a hook is present and owned by anyone at all.
    ///
    /// A delegated hook still runs its manager's gate, so `doctor --strict`
    /// must not call it missing.
    #[must_use]
    pub fn is_satisfied(self) -> bool {
        !matches!(self, Self::Absent | Self::Foreign)
    }

    /// Stable label for JSON output.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Absent => "absent",
            Self::Managed => "managed",
            Self::PreCommit => "delegated_pre_commit",
            Self::HooksPath => "delegated_hooks_path",
            Self::Foreign => "foreign",
        }
    }
}

/// Ownership of the three hooks do-harness manages.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct HookOwnership {
    /// Owner of the `pre-commit` hook.
    pub pre_commit: HookOwner,
    /// Owner of the `pre-push` hook.
    pub pre_push: HookOwner,
    /// Owner of the `commit-msg` hook.
    pub commit_msg: HookOwner,
}

impl HookOwnership {
    /// Whether every hook is managed by do-harness or delegated to a known owner.
    #[must_use]
    pub fn is_satisfied(self) -> bool {
        self.pre_commit.is_satisfied()
            && self.pre_push.is_satisfied()
            && self.commit_msg.is_satisfied()
    }
}

/// Whether the repository root carries a pre-commit framework configuration.
#[must_use]
pub fn has_pre_commit_config(repo_root: &Path) -> bool {
    repo_root.join(PRE_COMMIT_CONFIG).is_file()
}

/// Classifies the hook file at `path`.
///
/// `pre_commit_config` is [`has_pre_commit_config`] for this repository and
/// `custom_hooks_path` says whether `core.hooksPath` points away from
/// `.git/hooks`. A wrapper's exact text is a weaker signal than the
/// declaration, since an installed wrapper can be rewritten by a version
/// upgrade or wrapped again by another manager, so a declared pre-commit
/// configuration attributes a runnable foreign file to pre-commit; a foreign
/// file in a configured hooks directory is attributed to that directory.
///
/// An empty file, or one git would skip for lack of an execute bit, is
/// [`HookOwner::Foreign`]: it runs no gate, so it cannot satisfy strict mode
/// merely because the repository declares a hook configuration.
#[must_use]
pub fn classify(path: &Path, pre_commit_config: bool, custom_hooks_path: bool) -> HookOwner {
    let Ok(content) = fs::read_to_string(path) else {
        return HookOwner::Absent;
    };
    if content.contains(MARKER) {
        return HookOwner::Managed;
    }
    if content.trim().is_empty() || !crate::fs_perm::is_owner_exec(path) {
        return HookOwner::Foreign;
    }
    if content.contains(PRE_COMMIT_WRAPPER_MARKER) {
        HookOwner::PreCommit
    } else if custom_hooks_path {
        HookOwner::HooksPath
    } else if pre_commit_config {
        HookOwner::PreCommit
    } else {
        HookOwner::Foreign
    }
}

/// Whether `content` is a hook wrapper generated by the pre-commit framework.
#[must_use]
pub fn is_pre_commit_wrapper(content: &str) -> bool {
    content.contains(PRE_COMMIT_WRAPPER_MARKER)
}

